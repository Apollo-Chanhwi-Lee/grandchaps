def _merge(base: dict, add: dict) -> dict:
    out = copy.deepcopy(base)
    for k, v in add.items():
        if k == "inherits":
            continue
        out[k] = _merge(out[k], v) if isinstance(v, dict) and isinstance(out.get(k), dict) else copy.deepcopy(v)
    return out


def _resolve(g: str, seen: tuple = ()) -> dict:
    if g in seen:
        raise ValueError(f"inheritance cycle: {' -> '.join(seen + (g,))}")
    own = _OWN[g]
    out: dict = {}
    for base in own.get("inherits", []):
        out = _merge(out, _resolve(base, seen + (g,)))
    out = _merge(out, own)
    out["inherits"] = list(own.get("inherits", []))
    pats = out.get("patterns") or {}
    out["patterns"] = {i: pats.get(i, g) for i in INSTRUMENT_PATTERNS}     # default: the genre's own patterns
    return out


